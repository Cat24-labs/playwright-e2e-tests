/** 
 * Arithmetic operators
 * Basic: +, -, *, /, **
 * Others
 * %, ++, --
 * 
 */

// Use Case 1: % Find a reminder
let a = 5
console.log(5 % 2) // 1
// Use Case 2: Increment and decrement
for (let i = 0; i <= 10; i++) { // increment
    console.log(i)
}

for (let i = 10; i >= 0; i--) { // decrement
    console.log(i)
}

// Use Case 3: Unary plus
let c = ("5" + 5) // 55
console.log(+c) 